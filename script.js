function applyLanguage(language) {
  const dictionary = translations[language] || translations.ru;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value !== undefined) element.placeholder = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });

  languageSelects.forEach((select) => {
    select.value = language;
    select.setAttribute("aria-label", dictionary["language.label"]);
  });

  const menuToggle = document.querySelector(".menu-toggle");
  if (menuToggle) {
    const menuKey =
      menuToggle.getAttribute("aria-expanded") === "true"
        ? "menu.close"
        : "menu.open";
    menuToggle.setAttribute("aria-label", dictionary[menuKey]);
  }

  document.title = dictionary[`page.${pageKey}`] || dictionary["page.home"];
  localStorage.setItem("moxito-language", language);
}

